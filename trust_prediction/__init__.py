"""
trust_prediction — программа автоматизации прогнозирования доверия приложения
по ГОСТ Р ИСО/МЭК 27034-7-2020 «Информационные технологии. Безопасность
приложений. Часть 7. Основы прогнозирования доверия» (идентичен
ISO/IEC 27034-7:2018, Assurance prediction framework).

Пакет реализует основные понятия и процесс стандарта:

    МОБП  — мера (меры) обеспечения безопасности приложений
    НСО   — нормативная структура организации (ONF)
    НСП   — нормативная структура приложения (ANF)
    ПОБП  — прогнозное обоснование безопасности приложения (PASR)

    Фактический уровень доверия  — достигнут реальным выполнением МОБП
    Ожидаемый уровень доверия    — фактический + перенесённый через ПОБП
    Целевой уровень доверия      — требуемый уровень, заданный владельцем

Модули:

    models           — доменные сущности и перечисления
    storage          — постоянное хранение состояния (JSON-репозиторий)
    substantiality   — эвристика оценки существенности изменений (п.7)
    raci             — матрица ответственности RACI (п.9.5, раздел 12)
    pasr             — построение и утверждение ПОБП (раздел 9)
    trust            — расчёт уровней доверия (раздел 5, 8)
    audit            — аудит и верификация ПОБП (разделы 10-11)
    workflow         — оркестрация десятишагового процесса (раздел 12)
    report           — формирование отчёта об ожидаемом уровне доверия (13)

ВАЖНО: эвристика оценки существенности изменений (substantiality.py) —
это вспомогательный инструмент поддержки принятия решений. Сам стандарт
(п. 7.1) прямо указывает, что закрытого перечня признаков существенности
не существует и решение принимается на основе анализа риска в контексте
конкретного приложения. Программа не заменяет этот анализ, а
структурирует и документирует его.
"""

